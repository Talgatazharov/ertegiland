export const storyQuality =
  "Қызықты балалар ертегісін жаз. 2–4 қысқа абзац, 120–200 сөз шамасында. Бір көркем деталь, нақты әрекет, тосын жаңалық, табиғи диалог және келесі бөлімге қызықтыратын интрига болсын. Үстірт әрекеттер тізбегін жазба. Кейіпкердің мәселені шешу тәсілі оқиғадан көрінсін. Үш таңдау әртүрлі әрекетке, ортаға немесе серікке алып барсын; таңдауды тек қайталап жазып, бірдей нәтижеге жеткізбе.";
export const chapterStages = [
  "Кіріспе",
  "Алғашқы жұмбақ",
  "Жаңа серік немесе кедергі",
  "Маңызды таңдау",
  "Шарықтау шегі",
  "Қорытынды",
];
export function characterPrompt(id: string, task: string) {
  const c = getCharacter(id);
  return [
    safetyPrompt,
    "ТҰРАҚТЫ CHARACTER PROFILE (сервердегі сенімді профиль):",
    c.aiSystemPrompt,
    "Әдеби бейне туралы қысқаша мәлімет: " + c.description,
    "Әдеттегі мекендері: " + c.typicalLocations.join(", "),
    task,
  ].join("\n\n");
}
export function continuationPrompt(session: StorySession) {
  const chapter = session.currentChapter + 1;
  return characterPrompt(
    session.characterId,
    storyQuality +
      "\nCURRENT CHAPTER: " +
      chapter +
      "/6 — " +
      chapterStages[chapter - 1] +
      ". chapter дәл " +
      chapter +
      " болсын. story, dialogue, atmosphere, title, scene және memory толтырылсын. memory бұрын табылған заттарды, таныс серіктерді және ашылған белгілерді сақтасын. Жаңа бөлім соңғы таңдаудың нақты салдарын көрсетсін. Тарихтағы затты жоғалтсаң не қолдансаң, себебін түсіндір. " +
      (chapter === 6
        ? "Барлық түйінді қисынды шеш, өткен таңдауларды қорытындыда еске ал. isEnding=true; choices=[]."
        : "Оқиға әлі аяқталмасын. isEnding=false; choices ішінде дәл 3 мағыналы, қайталанбайтын таңдау болсын."),
  );
}
