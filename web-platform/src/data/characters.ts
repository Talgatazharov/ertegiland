type ProfileSeed = Omit<
  CharacterProfile,
  "aiSystemPrompt" | "image" | "imageCredit"
>;
function profile(seed: ProfileSeed): CharacterProfile {
  return {
    ...seed,
    image: seed.imageSlug
      ? "/characters/" + seed.imageSlug + "-960.webp"
      : null,
    imageCredit: seed.imageSlug
      ? "Persony.zip — пайдаланушы ұсынған көркем бейне"
      : "Жобаның бұрынғы көркем бейнесі. Архивте Кендебай суреті жоқ.",
    aiSystemPrompt: [
      "Сен " +
        seed.name +
        " кейіпкерінің әдеби бейнесін сомдайсың. Бұл жаңа қиял әңгіме, түпнұсқа дәйексөз емес.",
      "Рөлі: " +
        seed.role +
        ". Мінезі: " +
        seed.personality.join(", ") +
        ". Құндылықтары: " +
        seed.values.join(", ") +
        ".",
      "Сөйлеу мәнері: " +
        seed.speakingStyle +
        ". Эмоциялық сипаты: " +
        seed.emotionalStyle +
        ".",
      "Мәселені шешу тәсілі: " +
        seed.problemSolvingStyle +
        ". Күшті жақтары: " +
        seed.strengths.join(", ") +
        ".",
      "Оқиға мәнері: " +
        seed.storyStyle +
        ". Тақырыптар: " +
        seed.storyThemes.join(", ") +
        ". Тапсырмалар: " +
        seed.taskTypes.join(", ") +
        ".",
      "Мінезіңді өзгертпе. Басқа кейіпкерлерге еліктеме. Қауіпті әрекет ұсынба. Кейіпкердің өмірбаянын жаңадан ойдан шығарып, нақты дерек деме.",
    ].join("\n"),
  };
}
