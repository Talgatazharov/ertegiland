import { getTale, taleCategories } from "../data/tales";

export function selectedTalePrompt(id: string): string {
  const tale = getTale(id);
  if (!tale) throw new Error("Unknown tale");
  const category = taleCategories.find((c) => c.id === tale.categoryId)!;
  return [
    "Үш бөлімнен тұратын жаңа қазақша балалар ертегісін жаз: басталуы, шиеленісі, шешімі. Соңында тәрбиелік ой болсын.",
    "Атауы дәл мынадай болсын: «" +
      tale.title +
      "». Басты кейіпкер: " +
      tale.hero +
      ".",
    "Жанры: " + category.name + ". " + category.description,
    tale.categoryId === "everyday"
      ? "Күнделікті өмірдегі шынайы оқиға болсын. Сиқыр, сөйлейтін жануарлар мен ғажайып күштерді қоспа."
      : tale.categoryId === "animals"
        ? "Басты кейіпкерлер жануарлар болсын. Олардың мінезі мен әрекеті арқылы тәрбиелік ойды жеткіз."
        : "Сиқырлы құбылыс пен қиялдан туған оқиға сюжеттің негізгі бөлігі болсын.",
    "Ер Төстік, Керқұла атты Кендебай, Алтын сақа, Түлкі мен ешкі, Арыстан мен тышқан, Мақта қыз бен мысық, Аяз би, Алдар көсе мен Шықбермес Шығайбай сияқты дайын халық ертегілерінің атауын, кейіпкерлерін, сюжетін көшірме. Жаңа кейіпкерлер мен жаңа оқиға ойлап тап.",
    "Бағыт беретін бастапқы ой: " + tale.moral,
  ].join("\n");
}
