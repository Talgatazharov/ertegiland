const emptyMemory = (): StoryMemory => ({
  items: [],
  allies: [],
  discoveries: [],
});
const add = (list: string[], value: string) =>
  Array.from(new Set([...list, value]));
export function initialChapter(characterId: string): StoryChapter {
  const a = adventures[getCharacter(characterId).id];
  return {
    chapter: 1,
    title: a.title,
    story: a.intro,
    dialogue: a.dialogue,
    atmosphere: a.atmosphere,
    scene: "steppe",
    memory: emptyMemory(),
    choices: a.paths.map((p) => ({ id: p.id, emoji: p.emoji, text: p.label })),
    isEnding: false,
    source: "demo",
  };
}
